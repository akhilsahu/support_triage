def is_excerpt_grounded(excerpt: str, clean_text: str) -> bool:
    """
    Validates whether an evidence excerpt generated by LLM is truly grounded in the cleaned text content.
    Handles minor LLM formatting, punctuation, and whitespace variations using:
    1. Direct normalized substring check
    2. Alphanumeric-only substring check
    3. Key word token overlap matching (>=70% of significant words present in source text)
    """
    if not excerpt or not clean_text:
        return False
    
    # 1. Direct normalized substring check (lowercased, collapsed whitespace)
    clean_norm = re.sub(r'\s+', ' ', clean_text.lower())
    excerpt_norm = re.sub(r'\s+', ' ', excerpt.lower())
    if excerpt_norm in clean_norm or (len(excerpt_norm) > 15 and excerpt_norm[:20] in clean_norm):
        return True

    # 2. Alphanumeric-only substring check (ignores punctuation, symbols, hyphens)
    clean_alpha = re.sub(r'[^a-z0-9]', '', clean_text.lower())
    excerpt_alpha = re.sub(r'[^a-z0-9]', '', excerpt.lower())
    if len(excerpt_alpha) >= 10 and excerpt_alpha in clean_alpha:
        return True

    # 3. Key word token overlap check for formatted or slightly modified quotes
    excerpt_words = set(w.lower() for w in re.findall(r'\b[a-z0-9]{3,}\b', excerpt.lower()))
    if not excerpt_words:
        return len(excerpt_alpha) >= 5 and excerpt_alpha in clean_alpha

    clean_words = set(w.lower() for w in re.findall(r'\b[a-z0-9]{3,}\b', clean_text.lower()))
    matches = excerpt_words.intersection(clean_words)
    overlap_ratio = len(matches) / len(excerpt_words)
    
    logger.debug(f"Grounding keyword check: overlap={overlap_ratio:.2f} for excerpt='{excerpt[:30]}...'")
    return overlap_ratio >= 0.70



async def _run_llm_fact_extraction(target_url: str, title: str, clean_text: str) -> List[Dict[str, str]]:
    """
    Sends the cleaned text snippet to LLM provider using get_async_openai_clients,
    and returns grounded facts verified by is_excerpt_grounded.
    """
    facts: List[Dict[str, str]] = []
    if not clean_text or len(clean_text) < 30:
        return facts

    snippet = clean_text[:4000].strip()
    from app.yullo.prompts.sources import (
        PREVIEW_FACT_EXTRACTION_SYSTEM_PROMPT as system_prompt,
        build_preview_fact_extraction_user_prompt,
    )

    try:
        # Use LLM provider factory respecting LLM_PROVIDER_PRIORITY fallback chain
        providers = get_async_openai_clients(override_model=settings.YULLO_ABOUT_MODEL)
        if not providers:
            logger.warning("No LLM providers configured/available for preview fact extraction.")
            return facts

        user_msg = build_preview_fact_extraction_user_prompt(target_url, title, snippet)

        for provider_name, client, model_name in providers:
            try:
                logger.info(f"Attempting preview fact extraction via provider '{provider_name}' with model '{model_name}'")
                
                completion_kwargs = {
                    "model": model_name,
                    "messages": [
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_msg}
                    ],
                    "temperature": 0.1,
                }
                # Support newer OpenAI model parameter schema (max_completion_tokens)
                if any(m in model_name.lower() for m in ["gpt-5", "o1", "o3", "o4"]):
                    completion_kwargs["max_completion_tokens"] = 400
                else:
                    completion_kwargs["max_tokens"] = 400

                try:
                    response = await client.chat.completions.create(**completion_kwargs)
                except Exception as param_err:
                    if "max_tokens" in str(param_err):
                        completion_kwargs.pop("max_tokens", None)
                        completion_kwargs["max_completion_tokens"] = 400
                        response = await client.chat.completions.create(**completion_kwargs)
                    else:
                        raise param_err

                raw_content = response.choices[0].message.content or ""
                if raw_content.strip():
                    c = raw_content.strip()
                    if c.startswith("```"):
                        c = c.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
                    parsed = json.loads(c)
                    raw_facts = parsed.get("facts", []) if isinstance(parsed, dict) else []

                    # Grounding Verification: Verify evidence_excerpt against clean_text
                    for rf in raw_facts:
                        text_str = str(rf.get("text") or "").strip()
                        excerpt_str = str(rf.get("evidence_excerpt") or "").strip()
                        locator_str = str(rf.get("source_locator") or target_url).strip()

                        if text_str and excerpt_str:
                            if is_excerpt_grounded(excerpt_str, clean_text):
                                facts.append({
                                    "text": text_str,
                                    "evidence_excerpt": excerpt_str,
                                    "source_locator": locator_str
                                })
                            else:
                                logger.info(f"Rejected ungrounded fact excerpt: '{excerpt_str}' for URL '{target_url}'")
                    
                    if facts:
                        # Successfully extracted grounded facts from this provider
                        break
            except Exception as prov_err:
                logger.warning(f"LLM provider '{provider_name}' failed for '{target_url}': {prov_err}")
                continue

    except Exception as e:
        logger.warning(f"LLM preview fact extraction failed for '{target_url}': {e}", exc_info=True)

    return facts


async def extract_and_persist_link_preview(
    db: AsyncSession,
    *,
    user_id: uuid.UUID,
    space_id: uuid.UUID,
    item_id: uuid.UUID,
    url: str
) -> Dict[str, Any]:
    """
    Extracts grounded facts from a URL using scraper core and LLM provider abstraction,
    verifies excerpt evidence against cleaned page content, and persists the preview state to KnowledgeBaseItem.
    Falls back to Firecrawl deep scraper if quick scraping returns 0 grounded facts.
    """
    # 1. Enforce Space ownership boundary
    stmt = select(Space).where(Space.id == space_id, Space.owner_user_id == user_id)
    owned_space = await db.scalar(stmt)
    if not owned_space:
        logger.warning(f"extract_and_persist_link_preview: Space {space_id} not owned by user {user_id}")
        return {
            "status": "unavailable",
            "title": url,
            "facts": [],
            "target_badges": ["About", "Category", "Aura knowledge"],
            "raw_text": "",
            "is_confirmed": False
        }

    # Fetch KnowledgeBaseItem
    kb_item = await db.get(KnowledgeBaseItem, item_id)
    if not kb_item or kb_item.space_id != space_id:
        logger.warning(f"extract_and_persist_link_preview: KnowledgeBaseItem {item_id} not found in space {space_id}")
        return {
            "status": "unavailable",
            "title": url,
            "facts": [],
            "target_badges": ["About", "Category", "Aura knowledge"],
            "raw_text": "",
            "is_confirmed": False
        }

    target_url = url.strip()
    if not target_url.startswith(("http://", "https://")):
        target_url = f"https://{target_url}"

    domain = urlparse(target_url).netloc.replace("www.", "") or target_url
    title = domain
    clean_text = ""
    status = "unavailable"
    provenance = "scraper_llm_grounded"

    # 2. Fetch and clean page content using quick scraper mode
    page_assets: Dict[str, Any] = {
        "favicon_url": None,
        "preview_image_url": None,
        "logo_url": None,
        "description": None,
        "images": [],
        "documents": [],
    }
    try:
        from app.orchestra.ai.ingestion.scraper import fetch_url
        page = await fetch_url(target_url, mode="quick")
        if page.title:
            title = page.title.strip()
        if page.raw:
            # Extract brand assets, preview images, and downloadable media
            from app.yullo.services.sources.asset_extractor import extract_page_assets
            page_assets = extract_page_assets(page.raw, target_url)

            soup = BeautifulSoup(page.raw, "html.parser")
            if (not title or title == domain) and soup.title and soup.title.string:
                title = soup.title.string.strip()
            # Strip non-content / script elements (keeping header, footer, nav for e-commerce/landing sites)
            for element in soup(["script", "style", "svg", "noscript", "iframe"]):
                element.extract()
            clean_text = soup.get_text(separator=" ", strip=True)
    except Exception as e:
        logger.warning(f"Quick scraper fetch failed for '{target_url}': {e}")
        clean_text = ""

    # If quick scrape yielded insufficient text (e.g. client-rendered SPAs like SpaceX, React apps, or bot challenges),
    # fall back to the existing ingestion deep scraper (Firecrawl / headless browser).
    if len(clean_text) < 30:
        logger.info(f"Quick scrape yielded sparse text ({len(clean_text)} chars) for '{target_url}'. Falling back to existing deep scraper.")
        try:
            deep_page = await fetch_url(target_url, mode="deep")
            if deep_page.title and (not title or title == domain):
                title = deep_page.title.strip()
            if deep_page.raw:
                deep_text = deep_page.raw.decode("utf-8", errors="ignore").strip()
                if len(deep_text) >= 30:
                    clean_text = deep_text
                    provenance = "scraper_deep_existing"

                    # Extract rich images, links, and documents from deep rendered markdown
                    from app.yullo.services.sources.asset_extractor import extract_markdown_assets
                    deep_assets = extract_markdown_assets(deep_text, target_url)
                    if not page_assets.get("images") and deep_assets.get("images"):
                        page_assets["images"] = deep_assets["images"]
                    if not page_assets.get("documents") and deep_assets.get("documents"):
                        page_assets["documents"] = deep_assets["documents"]
                    if not page_assets.get("links") and deep_assets.get("links"):
                        page_assets["links"] = deep_assets["links"]
                    if not page_assets.get("preview_image_url") and page_assets["images"]:
                        page_assets["preview_image_url"] = page_assets["images"][0]["url"]
        except Exception as deep_err:
            logger.warning(f"Existing deep scraper fallback failed for '{target_url}': {deep_err}")

    # If clean_text is still under 30 chars, fall back to meta description if available
    if len(clean_text) < 30 and page_assets.get("description"):
        meta_desc = page_assets["description"].strip()
        if len(meta_desc) >= 30:
            clean_text = meta_desc

    # 5. Extract grounded page facts using LLM provider abstraction
    facts: List[Dict[str, str]] = []
    if clean_text and len(clean_text) >= 30:
        logger.info(
            "preview.fact_extraction.starting",
            target_url=target_url,
            clean_text_len=len(clean_text),
            space_id=str(space_id),
            item_id=str(item_id),
        )
        try:
            facts = await _run_llm_fact_extraction(target_url, title, clean_text)
            logger.info(
                "preview.fact_extraction.completed",
                target_url=target_url,
                extracted_count=len(facts),
            )
        except Exception as fact_err:
            logger.error(
                "preview.fact_extraction.failed",
                target_url=target_url,
                error=str(fact_err),
                exc_info=True,
            )

    # 6. Determine final status
    # When facts are successfully extracted, the source is ready for owner review.
    # If text is present but 0 facts were found, it is ready_to_review so the owner can inspect the excerpt.
    if facts and len(facts) >= 1:
        status = "ready"
    elif clean_text and len(clean_text) >= 30:
        status = "ready_to_review"
    elif status != "unavailable":
        status = "insufficient_context"

    target_badges = ["About", "Category", "Aura knowledge"]
    raw_text_snippet = clean_text[:1200] if clean_text else f"Source URL: {target_url}"

    favicon_url = page_assets.get("favicon_url")
    preview_image_url = page_assets.get("preview_image_url")
    logo_url = page_assets.get("logo_url")

    source_metadata = kb_item.source_metadata or {}
    source_metadata.update({
        "status": status,
        "prompt_version": PROMPT_VERSION,
        "source_version": kb_item.source_version or 1,
        "raw_text": raw_text_snippet,
        "target_badges": target_badges,
        "is_confirmed": False,
        "provenance": provenance,
        "favicon_url": favicon_url,
        "preview_image_url": preview_image_url,
        "logo_url": logo_url,
        "assets": page_assets,
    })

    # Keep an owner-supplied label. When the initial title is only the URL,
    # replace it with the scraped page title for a friendlier source list.
    persisted_title = (
        kb_item.title
        if kb_item.title and kb_item.title != target_url
        else (title or domain)
    )
    kb_item.title = persisted_title
    kb_item.extracted_facts = facts[:4]
    kb_item.source_metadata = source_metadata
    kb_item.ingestion_status = status
    db.add(kb_item)

    # Persist extracted preview facts to KBFact table so they are immediately available
    # in the SourceReviewSheet for human verification/confirmation without waiting for full ingestion.
    if facts:
        from app.models.kb_fact import KBFact
        from sqlalchemy import select as sa_select

        # Check existing facts for this source item to avoid inserting duplicates on re-preview
        existing_facts = (
            await db.scalars(
                sa_select(KBFact).where(
                    KBFact.source_item_id == kb_item.id,
                    KBFact.space_id == space_id,
                )
            )
        ).all()
        existing_values = {ef.value.strip().casefold() for ef in existing_facts if ef.value}

        for f in facts[:4]:
            val = (f.get("text") or "").strip()
            if val and val.casefold() not in existing_values:
                kbf = KBFact(
                    kb_id=kb_item.kb_id,
                    space_id=kb_item.space_id,
                    subject=persisted_title,
                    label="Overview",
                    value=val,
                    note=(f.get("evidence_excerpt") or "").strip(),
                    review_status="extracted",
                    verified=False,
                    source_item_id=kb_item.id,
                    source_filename=persisted_title,
                    source_version=kb_item.source_version or 1,
                )
                db.add(kbf)
                existing_values.add(val.casefold())

    await db.commit()

    return {
        "status": status,
        "title": persisted_title,
        "facts": facts,
        "target_badges": target_badges,
        "raw_text": raw_text_snippet,
        "is_confirmed": False,
        "prompt_version": PROMPT_VERSION,
        "source_version": kb_item.source_version or 1,
        "favicon_url": favicon_url,
        "preview_image_url": preview_image_url,
        "logo_url": logo_url,
        "assets": page_assets,
    }
