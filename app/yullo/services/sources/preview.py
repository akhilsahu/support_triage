async def extract_and_persist_link_preview(
    db: AsyncSession,
    *,
    user_id: uuid.UUID,
    space_id: uuid.UUID,
    item_id: uuid.UUID,
    url: str
) -> Dict[str, Any]:
    """
    Extracts grounded facts from a URL using scraper core and LLM provider abstraction,
    verifies excerpt evidence against cleaned page content, and persists the preview state to KnowledgeBaseItem.
    Falls back to Firecrawl deep scraper if quick scraping returns 0 grounded facts.
    """
    # 1. Enforce Space ownership boundary
    stmt = select(Space).where(Space.id == space_id, Space.owner_user_id == user_id)
    owned_space = await db.scalar(stmt)
    if not owned_space:
        logger.warning(f"extract_and_persist_link_preview: Space {space_id} not owned by user {user_id}")
        return {
            "status": "unavailable",
            "title": url,
            "facts": [],
            "target_badges": ["About", "Category", "Aura knowledge"],
            "raw_text": "",
            "is_confirmed": False
        }

    # Fetch KnowledgeBaseItem
    kb_item = await db.get(KnowledgeBaseItem, item_id)
    if not kb_item or kb_item.space_id != space_id:
        logger.warning(f"extract_and_persist_link_preview: KnowledgeBaseItem {item_id} not found in space {space_id}")
        return {
            "status": "unavailable",
            "title": url,
            "facts": [],
            "target_badges": ["About", "Category", "Aura knowledge"],
            "raw_text": "",
            "is_confirmed": False
        }

    target_url = url.strip()
    if not target_url.startswith(("http://", "https://")):
        target_url = f"https://{target_url}"

    # 2. Emit progress: Scraping page
    await source_stream.emit_progress(db, space_id=space_id, source_id=item_id, progress=25, stage="Reading website content...")

    # Fetch and clean page content via shared Smart Scraper engine
    scrape_res = await smart_scrape_url(
        target_url,
        space_id=space_id,
        item_id=item_id,
    )

    domain = scrape_res.domain or urlparse(target_url).netloc.replace("www.", "") or target_url
    title = scrape_res.title or domain
    clean_text = scrape_res.clean_text
    page_assets = scrape_res.page_assets
    provenance = scrape_res.provenance
    status = "unavailable"

    # 5. Extract grounded page facts and structured entities
    facts: List[Dict[str, str]] = []
    entity_candidates = []
    if clean_text and len(clean_text) >= 30:
        logger.info(
            "preview.extraction.starting",
            target_url=target_url,
            clean_text_len=len(clean_text),
            space_id=str(space_id),
            item_id=str(item_id),
        )

        await source_stream.emit_progress(
            db,
            space_id=space_id,
            source_id=item_id,
            progress=45,
            stage="Analyzing facts from page...",
        )

        # 5a. Extract preliminary facts FIRST (~3 seconds)
        try:
            facts = await _run_llm_fact_extraction(target_url, title, clean_text)
            logger.info(
                "preview.fact_extraction.completed",
                target_url=target_url,
                extracted_count=len(facts),
            )
        except Exception as fact_err:
            logger.error(
                "preview.fact_extraction.failed",
                target_url=target_url,
                error=str(fact_err),
                exc_info=True,
            )
            facts = []

        # 5b. Stream preliminary facts to UI IMMEDIATELY (within 5-10s)
        if facts:
            await source_stream.emit_facts_streamed(
                db,
                space_id=space_id,
                source_id=item_id,
                facts=facts,
                progress=65,
                stage="Preliminary facts extracted",
            )

        # 5c. Extract structured entities (bounded preview chunks so it completes in <= 15s)
        from app.config import settings
        if settings.YULLO_ENTITY_EXTRACTION_ENABLED:
            await source_stream.emit_progress(
                db,
                space_id=space_id,
                source_id=item_id,
                progress=80,
                stage="Extracting structured details...",
            )
            try:
                from app.yullo.services.entities.provider import LLMEntityExtractionProvider
                from app.yullo.services.entities.extraction import extract_entity_candidates
                provider = LLMEntityExtractionProvider()
                # Focus preview on top 18,000 characters for sub-20s response
                preview_chunk = clean_text[:18000]
                entity_candidates = await extract_entity_candidates(
                    source_item_id=kb_item.id,
                    source_version=kb_item.source_version or 1,
                    provider=provider,
                    source_text=preview_chunk,
                )
                logger.info(
                    "preview.entity_extraction.completed",
                    target_url=target_url,
                    extracted_count=len(entity_candidates),
                )
            except Exception as entity_err:
                logger.error(
                    "preview.entity_extraction.failed",
                    target_url=target_url,
                    error=str(entity_err),
                    exc_info=True,
                )
                entity_candidates = []

    # 6. Determine final status
    # When facts or structured entities are successfully extracted, the source is ready for owner review.
    # If text is present but 0 facts/entities were found, it is ready_to_review so the owner can inspect the excerpt.
    if (facts and len(facts) >= 1) or (entity_candidates and len(entity_candidates) >= 1):
        status = "ready"
    elif clean_text and len(clean_text) >= 30:
        status = "ready_to_review"
    elif status != "unavailable":
        status = "insufficient_context"

    target_badges = ["About", "Category", "Aura knowledge"]
    raw_text_snippet = clean_text[:1200] if clean_text else f"Source URL: {target_url}"

    favicon_url = page_assets.get("favicon_url")
    preview_image_url = page_assets.get("preview_image_url")
    logo_url = page_assets.get("logo_url")

    source_metadata = kb_item.source_metadata or {}
    source_metadata.update({
        "status": status,
        "prompt_version": PROMPT_VERSION,
        "source_version": kb_item.source_version or 1,
        "raw_text": raw_text_snippet,
        "target_badges": target_badges,
        "is_confirmed": False,
        "provenance": provenance,
        "favicon_url": favicon_url,
        "preview_image_url": preview_image_url,
        "logo_url": logo_url,
        "assets": page_assets,
        "raw_html_path": page_assets.get("raw_html_path"),
        "raw_deep_path": page_assets.get("raw_deep_path"),
        "entity_extraction_status": "done" if entity_candidates else ("no_entities_found" if clean_text else None),
    })

    # Keep an owner-supplied label. When the initial title is only the URL,
    # replace it with the scraped page title for a friendlier source list.
    persisted_title = (
        kb_item.title
        if kb_item.title and kb_item.title != target_url
        else (title or domain)
    )
    kb_item.title = persisted_title
    kb_item.extracted_facts = facts[:4]
    kb_item.source_metadata = source_metadata
    kb_item.ingestion_status = status
    db.add(kb_item)

    # Persist extracted preview facts to KBFact table so they are immediately available
    # in the SourceReviewSheet for human verification/confirmation without waiting for full ingestion.
    if facts:
        from app.models.kb_fact import KBFact
        from sqlalchemy import select as sa_select

        # Check existing facts for this source item to avoid inserting duplicates on re-preview
        existing_facts = (
            await db.scalars(
                sa_select(KBFact).where(
                    KBFact.source_item_id == kb_item.id,
                    KBFact.space_id == space_id,
                )
            )
        ).all()
        existing_values = {ef.value.strip().casefold() for ef in existing_facts if ef.value}

        for f in facts[:4]:
            val = (f.get("text") or "").strip()
            if val and val.casefold() not in existing_values:
                kbf = KBFact(
                    kb_id=kb_item.kb_id,
                    space_id=kb_item.space_id,
                    subject=persisted_title,
                    label="Overview",
                    value=val,
                    note=(f.get("evidence_excerpt") or "").strip(),
                    review_status="extracted",
                    verified=False,
                    source_item_id=kb_item.id,
                    source_filename=persisted_title,
                    source_version=kb_item.source_version or 1,
                )
                db.add(kbf)
                existing_values.add(val.casefold())

    # Persist extracted structured entity candidates into YulloSpaceEntity & YulloSpaceEntityEvidence
    if entity_candidates:
        from app.yullo.services.entities.extraction import persist_entity_candidates
        await persist_entity_candidates(
            db,
            source_item_id=kb_item.id,
            source_version=kb_item.source_version or 1,
            candidates=entity_candidates,
        )

    await db.commit()

    # Emit final completion through stream broadcaster
    await source_stream.emit_completed(
        db,
        space_id=space_id,
        source_id=kb_item.id,
        facts=facts,
        assets=page_assets,
        status=status,
    )

    return {
        "status": status,
        "title": persisted_title,
        "facts": facts,
        "target_badges": target_badges,
        "raw_text": raw_text_snippet,
        "is_confirmed": False,
        "prompt_version": PROMPT_VERSION,
        "source_version": kb_item.source_version or 1,
        "favicon_url": favicon_url,
        "preview_image_url": preview_image_url,
        "logo_url": logo_url,
        "assets": page_assets,
    }
